public class PrimitiveTypes {
    public static void main(String[] args){
        // Primitive data types in Java
        byte age = 20; // Byte
        short year = 2026; // Short
        int a = 20000; // Integer
        long population = 8_887_000_000L; // Long
        float myFloat = 3.14f; // Floating-point number
        double c = 15.953; // Floating-point number
        char d = 'A'; // Character
        boolean isJavaFun = true; // Boolean

        // Displaying the values of the primitive types
        System.out.println("Byte value: " + age);
        System.out.println("Short value: " + year);
        System.out.println("Integer value: " + a);
        System.out.println("Long value: " + population);
        System.out.println("Float value: " + myFloat);
        System.out.println("Double value: " + c);
        System.out.println("Character value: " + d);
        System.out.println("Boolean value: " + isJavaFun);
    }
}